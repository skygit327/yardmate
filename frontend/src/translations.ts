export function translate(text: string, language: Language): string {
  if (language === 'en') return text;
  const catalog = language === 'ko' ? korean : chinese;
  if (Object.hasOwn(catalog, text)) return catalog[text];
  return rules.reduce((value, [pattern, replacements]) =>
    value.replace(pattern, replacements[language] as string), text);
}
