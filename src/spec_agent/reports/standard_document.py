"""Render an inspection standard (one version) with its change history as PDF and Excel."""

import hashlib
import json
import os
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from spec_agent.reports.i18n import ReportTranslator, rich_text
from spec_agent.reports.rendering import cjk_font, font_name, latin_font
from spec_agent.schemas.standard import Standard
from spec_agent.services.versioning import rule_criteria

STATUS_TEXT = {
    "DRAFT": "Draft revision / Not yet activated",
    "ACTIVE": "Active standard",
    "SUPERSEDED": "Superseded / Do not use for new inspections",
}


def document_rows(standard: Standard, family: list[Standard], language: str = "en"):
    tr = ReportTranslator(language)
    metadata = [
        [tr.label("Customer"), standard.customer],
        [
            tr.label("Part number / Product"),
            f"{standard.part_number} / {tr.term(standard.product_name)}",
        ],
        [tr.label("Document number"), standard.document_number],
        [tr.label("Revision / Version"), f"{standard.revision} / v{standard.version}"],
        [tr.label("Status"), tr.label(STATUS_TEXT[standard.status])],
        [
            tr.label("Activated by / at"),
            f"{standard.activated_by or '-'} / {standard.activated_at or '-'}",
        ],
        [
            tr.label("Data provenance"),
            tr.label(
                "Synthetic data / Not company-approved"
                if standard.provenance == "SYNTHETIC"
                else "Internal reference"
            ),
        ],
    ]
    rules = [
        [tr.label("Area"), tr.label("Inspection item"), tr.label("Criteria"), tr.label("Source")]
    ]
    for rule in standard.rules:
        rules.append(
            [tr.term(rule.area), tr.term(rule.item), tr.phrase(rule_criteria(rule)), rule.source]
        )
    history = [
        [
            tr.label("No"),
            tr.label("Revision"),
            tr.label("Change"),
            tr.label("Date"),
            tr.label("Prepared / Activated"),
        ]
    ]
    number = 0
    for version in family:
        if version.version > standard.version:
            continue
        revised = [entry for entry in version.history if entry.kind in {"CREATED", "REVISED"}]
        activated = next((e for e in version.history if e.kind == "ACTIVATED"), None)
        summary = "\n".join(
            "\n".join(tr.phrase(line) for line in entry.summary.split("\n"))
            for entry in revised
            if entry.summary
        ) or (tr.label("Initial registration") if version.version == 1 else "-")
        prepared = ", ".join(dict.fromkeys(entry.actor for entry in revised)) or "-"
        date = (revised[-1].at if revised else version.created_at or "")[:10] or "-"
        number += 1
        history.append(
            [
                str(number),
                version.revision,
                summary,
                date,
                f"{prepared} / {activated.actor if activated else version.activated_by or '-'}",
            ]
        )
    texts = {
        "title": tr.label("Inspection Standard"),
        "status": tr.label(STATUS_TEXT[standard.status]),
        "generated": tr.label("Generated by Spec Agent"),
        "criteria": tr.label("Criteria"),
        "history": tr.label("Change history"),
        "signatures": tr.label(
            "Prepared: ____________  Reviewed: ____________  Approved: ____________"
        ),
        "sheet": tr.label("Standard"),
        "translated": ""
        if tr.english
        else tr.label(
            "Translated from the English master. Customer sources and user-entered text are "
            "kept as written."
        ),
    }
    return metadata, rules, history, texts


def _table(rows, widths, style, cjk_font, header=True):
    def cell(value):
        return Paragraph(rich_text(value, cjk_font), style)

    table = Table([[cell(v) for v in row] for row in rows], colWidths=widths, repeatRows=1)
    commands = [
        ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#cbd5db")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    if header:
        commands.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dbeee8")))
    else:
        commands.append(("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eef3f5")))
    table.setStyle(TableStyle(commands))
    return table


def render_pdf(path: Path, standard: Standard, rows, font: str):
    metadata, rules, history, texts = rows
    style = ParagraphStyle("body", fontName=latin_font(), fontSize=8, leading=11)
    heading = ParagraphStyle("heading", parent=style, fontSize=17, leading=24, spaceAfter=8)
    sub = ParagraphStyle("sub", parent=style, fontSize=11, leading=16, spaceBefore=10, spaceAfter=6)

    def text(value, paragraph_style=style):
        return Paragraph(rich_text(value, font), paragraph_style)

    story = [
        text(texts["title"], heading),
        text(f"{texts['status']} · {texts['generated']}"),
        *([text(texts["translated"])] if texts["translated"] else []),
        Spacer(1, 10),
        _table(metadata, [130, 640], style, font, header=False),
        text(texts["criteria"], sub),
        _table(rules, [110, 160, 300, 200], style, font),
        text(texts["history"], sub),
        _table(history, [30, 60, 450, 80, 150], style, font),
        Spacer(1, 14),
        text(texts["signatures"]),
    ]

    def footer(canvas, document):
        canvas.setFont(latin_font(), 8)
        canvas.drawRightString(
            landscape(A4)[0] - 36,
            22,
            f"{standard.document_number} Rev {standard.revision} · {document.page}",
        )

    SimpleDocTemplate(
        str(path),
        pagesize=landscape(A4),
        leftMargin=36,
        rightMargin=36,
        topMargin=30,
        bottomMargin=36,
        title=f"Inspection Standard {standard.document_number} Rev {standard.revision}",
    ).build(story, onFirstPage=footer, onLaterPages=footer)


def render_excel(path: Path, standard: Standard, rows):
    metadata, rules, history, texts = rows
    book = Workbook()
    sheet = book.active
    sheet.title = texts["sheet"][:31]
    sheet.append(
        [
            " · ".join(
                part for part in (texts["title"], texts["status"], texts["translated"]) if part
            )
        ]
    )
    for row in metadata:
        sheet.append(row)
    sheet.append([])
    header_rows = [sheet.max_row + 1]
    for row in rules:
        sheet.append(row)
    log = book.create_sheet(texts["history"][:31])
    for row in history:
        log.append(row)
    for target, widths, headers in (
        (sheet, (22, 30, 60, 50), [1, *header_rows]),
        (log, (6, 12, 80, 14, 30), [1]),
    ):
        for row in target.iter_rows():
            for cell in row:
                if isinstance(cell.value, str):
                    cell.data_type = "s"
                cell.font = Font(name="Arial", size=10)
                cell.alignment = Alignment(vertical="top", wrap_text=True)
        for index in headers:
            for cell in target[index]:
                cell.fill = PatternFill("solid", fgColor="DBEEE8")
                cell.font = Font(name="Arial", size=11, bold=True)
        for column, width in zip("ABCDE", widths, strict=False):
            target.column_dimensions[column].width = width
    book.save(path)


class StandardDocumentRenderer:
    def __init__(self, root: Path, font_path: Path | None):
        self.root = root
        self.font = font_name(font_path)
        latin_font()

    def __call__(
        self, standard: Standard, family: list[Standard], extension: str, language: str = "en"
    ) -> Path:
        rows = document_rows(standard, family, language)
        payload = json.dumps([standard.status, rows], ensure_ascii=False, sort_keys=True)
        digest = hashlib.sha256(payload.encode()).hexdigest()[:16]
        directory = self.root / standard.id
        directory.mkdir(parents=True, exist_ok=True)
        target = directory / f"standard-{digest}.{extension}"
        if not target.exists():
            temporary = directory / f"standard-{digest}.tmp.{extension}"
            if extension == "pdf":
                render_pdf(temporary, standard, rows, cjk_font(self.font, language))
            else:
                render_excel(temporary, standard, rows)
            os.replace(temporary, target)
        return target
